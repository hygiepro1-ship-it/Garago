/** Donne `tr("texte français")` : le texte dans la langue choisie par le garage. */
export type Tr = ((fr: string) => string) & { en: boolean; locale: string };

export function useTr(): Tr {
  const { lang } = useLang();
  const en = lang === "en";
  return Object.assign((fr: string) => (en ? DASHBOARD_EN[fr] ?? fr : fr), { en, locale: en ? "en-CA" : "fr-CA" });
}
